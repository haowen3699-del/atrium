/** 三个字符（二进制，下→上）转卦：如 "111"（下卦乾）+"110"（上卦兑）→ 履 */
export function hexFromLines(lines: number[]): HexData | null {
  const lower = lines.slice(0, 3).join("");
  const upper = lines.slice(3, 6).join("");
  const tri = Object.fromEntries(TRIGRAMS.map(([n, b]) => [b, n]));
  const lo = tri[lower];
  const up = tri[upper];
  if (!lo || !up) return null;
  return HEX[`${up}${lo}`] ?? null;
}

/** 三钱起卦：掷 6 次（从下往上），返回每爻 [0/1Yin/Yang, 是否动爻] */
function toss(): { val: number; moving: boolean } {
  const coins = [Math.random(), Math.random(), Math.random()];
  // 背=3、字=2
  const sum = coins.reduce((a, c) => a + (c < 0.5 ? 3 : 2), 0);
  if (sum === 9) return { val: 1, moving: true };  // 老阳（三背）
  if (sum === 7) return { val: 1, moving: false }; // 少阳（二背一字）
  if (sum === 8) return { val: 0, moving: false }; // 少阴（一背二字）
  return { val: 0, moving: true };                 // 老阴（三字）
}

export interface Cast {
  lines: number[];
  moving: number[];    // 动爻位置（1-6，从下往上）
  hex: HexData;
  changed: HexData | null; // 变卦（有动爻才存在）
  changedLines: number[] | null;
}

/** 起一卦：返回本卦（+ 变卦） */
export function cast(): Cast {
  const raw: { val: number; moving: boolean }[] = [];
  for (let i = 0; i < 6; i++) raw.push(toss());
  const lines = raw.map((r) => r.val);
  const moving = raw.map((r, i) => (r.moving ? i + 1 : 0)).filter(Boolean);
  const hex = hexFromLines(lines)!;
  let changed: HexData | null = null;
  let changedLines: number[] | null = null;
  if (moving.length) {
    const cl = lines.map((v, i) => (raw[i].moving ? 1 - v : v));
    changedLines = cl;
    changed = hexFromLines(cl) ?? null;
  }
  return { lines, moving, hex, changed, changedLines };
}

/** 画卦（六爻竖排，上→下）：+ 为阳（实线）、- 为阴（中间断） */
export function glyphOf(lines: number[]): string[] {
  return lines
    .slice()
    .reverse()
    .map((v) => (v === 1 ? "─────" : "─ ───"));
}