/* ===== 易经 · 挂画（梅花易数 · 三钱起卦）=====
 * 64 卦数据（通行本周易）+ 三钱起卦算法。
 * 三枚铜钱掷 6 次（从下往上成爻）：背=3、字=2，每次和值
 *   9 = 老阳（动爻，阳）  7 = 少阳（阳）
 *   8 = 少阴（阴）        6 = 老阴（动爻，阴）
 * 动爻翻转得到变卦。
 */

export interface HexLine {
  pos: string;   // 初九 / 六二 …
  text: string;  // 爻辞
  image: string; // 象曰（小象）
}

export interface HexData {
  n: number;
  name: string;   // 乾
  alias: string;  // 乾为天
  upper: string;  // 上卦
  lower: string;  // 下卦
  judgment: string; // 卦辞
  image: string;    // 象曰（大象）
  lines: HexLine[]; // 从下往上 6 爻
}

